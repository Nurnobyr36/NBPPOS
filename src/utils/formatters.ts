export function formatMoney(amount: number = 0, symbol: string = '৳'): string {
  const num = Number(amount) || 0;
  return `${symbol} ${num.toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

export function formatDate(dateString?: string, includeTime = false): string {
  if (!dateString) return '-';
  const date = new Date(dateString);
  if (isNaN(date.getTime())) return dateString;

  const options: Intl.DateTimeFormatOptions = {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    ...(includeTime ? { hour: '2-digit', minute: '2-digit', hour12: true } : {}),
  };
  return date.toLocaleDateString('bn-BD', options);
}

export function generateSku(prefix: string = 'PRD'): string {
  const rand = Math.floor(10000 + Math.random() * 90000);
  return `${prefix}-${rand}`;
}

export function generateBarcode(): string {
  // Generate valid 13-digit EAN style number
  let result = '890'; // Bangladesh prefix style or internal
  for (let i = 0; i < 9; i++) {
    result += Math.floor(Math.random() * 10);
  }
  // Check digit
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    sum += parseInt(result[i], 10) * (i % 2 === 0 ? 1 : 3);
  }
  const check = (10 - (sum % 10)) % 10;
  return result + check;
}

export function generateInvoiceNo(): string {
  const date = new Date();
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const rand = Math.floor(1000 + Math.random() * 9000);
  return `INV-${year}${month}-${rand}`;
}
